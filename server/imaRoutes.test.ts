import assert from "node:assert/strict";
import test from "node:test";
import express from "express";
import { once } from "node:events";
import type { Database } from "./types.js";
import type { Store } from "./db.js";
import { ImaService } from "./knowledge/imaService.js";
import { installImaRoutes } from "./imaRoutes.js";

test("ima HTTP routes enforce Key and ownership, ignore query identity, redact credentials and honor disable/revoke", async t => {
  const db = { users: ["a", "b", "employee"].map(id => ({ id, enabled: true, defaultWorkspaceId: id === "employee" ? "a" : id })), workspaces: ["a", "b"].map(id => ({ id, status: "active" })), workspaceMembers: [{ userId: "a", workspaceId: "a", role: "owner" }, { userId: "b", workspaceId: "b", role: "owner" }, { userId: "employee", workspaceId: "a", role: "member" }], knowledgeConnections: [], auditLogs: [] } as unknown as Database;
  const store = { async read() { return db; }, async mutate<T>(fn: (db: Database) => T) { return fn(db); } } as Store;
  let enabled = true, calls = 0, hostile = false;
  const service = new ImaService(store, (async (url) => {
    calls++;
    if (hostile) throw Error("secret echoed client-real-a api-real-secret-a");
    return Response.json({ code: 0, data: String(url).endsWith("search_knowledge_base") ? { info_list: [{ id: "kb-1", name: "当前账号知识库" }], is_end: true } : { note_folder_infos: [] } });
  }) as typeof fetch);
  const app = express(); app.use(express.json());
  installImaRoutes(app, [(req, res, next) => { const id = String(req.headers["x-fixture-key"] || ""); if (!db.users.some(u => u.id === id)) return res.sendStatus(428); req.user = db.users.find(u => u.id === id); req.workspaceId = id === "employee" ? "a" : id; next(); }], service, () => enabled);
  const server = app.listen(0, "127.0.0.1"); await once(server, "listening");
  t.after(() => { server.closeAllConnections(); server.close(); });
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}/api/knowledge/connections/ima`;
  const request = (id = "", method = "GET", body?: unknown, suffix = "") => fetch(base + suffix, { method, headers: { "x-fixture-key": id, "Content-Type": "application/json" }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const credentials = { clientId: "client-real-a", apiKey: "api-real-secret-a" };
  for (const method of ["GET", "PUT", "DELETE"]) assert.equal((await request("", method, method === "PUT" ? credentials : undefined)).status, 428);
  assert.equal((await request("employee", "PUT", credentials)).status, 403); assert.equal(calls, 0);
  assert.equal((await request("a", "PUT", { ...credentials, workspaceId: "b" })).status, 400); assert.equal(calls, 0);
  const connected = await request("a", "PUT", credentials, "?workspaceId=b&userId=b");
  assert.equal(connected.status, 200); assert.equal(connected.headers.get("cache-control"), "no-store");
  assert.doesNotMatch(await connected.text(), /client-real-a|api-real-secret-a|encrypted/);
  assert.equal(db.knowledgeConnections[0].workspaceId, "a");
  const other = await request("b", "GET", undefined, "?workspaceId=a");
  assert.doesNotMatch(await other.text(), /当前账号知识库|kb-1/);
  const restricted = await request("employee"); assert.equal(restricted.status, 200);
  const restrictedText = await restricted.text(); assert.match(restrictedText, /managementRestricted/); assert.doesNotMatch(restrictedText, /当前账号知识库|kb-1|encrypted/);
  assert.equal((await request("a", "PATCH", { selectedIds: ["foreign"] }, "/scope")).status, 400);
  assert.equal((await request("a", "PATCH", { selectedIds: [] }, "/scope")).status, 200);
  assert.equal((await request("a", "POST", undefined, "/check")).status, 200);
  assert.equal((await request("a", "POST", undefined, "/libraries/refresh")).status, 200);
  assert.equal((await request("a", "POST", { query: "个人知识库" }, "/libraries/refresh")).status, 200);
  assert.equal((await request("employee", "POST", { query: "个人知识库" }, "/libraries/refresh")).status, 403);
  assert.equal((await request("a", "POST", { query: "个人知识库", workspaceId: "b" }, "/libraries/refresh")).status, 400);
  assert.equal((await request("a", "POST", { query: " " }, "/libraries/refresh")).status, 400);
  assert.equal((await request("a", "POST", { query: { url: "https://example.com" } }, "/libraries/refresh")).status, 400);
  hostile = true;
  const failed = await request("a", "PUT", credentials); assert.equal(failed.status, 502);
  assert.doesNotMatch(await failed.text(), /secret|client-real-a|api-real-secret-a/);
  enabled = false;
  assert.equal((await request("a", "PUT", credentials)).status, 503);
  assert.equal((await (await request("a")).json()).configured, false);
  assert.equal((await request("a", "DELETE")).status, 200);
  assert.equal(db.knowledgeConnections[0].encryptedApiKey, undefined); assert.equal(db.knowledgeConnections[0].encryptedClientId, undefined);
});
